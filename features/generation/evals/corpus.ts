import {
  generationEvalCaseSchema,
  type EvalSurface,
  type GenerationEvalCase,
} from "@/features/generation/evals/contracts";

function evalCase(
  id: string,
  surface: EvalSurface,
  prompt: string,
  expectedScope: string,
  expectedMacrostructure: string,
  primaryInteraction: string,
  mustHave: string[],
  excluded: string[] = [],
  context: string[] = [],
  referenceArtifact?: { path: string; provenance: string },
): GenerationEvalCase {
  return generationEvalCaseSchema.parse({
    id,
    surface,
    prompt,
    expectedScope,
    expectedMacrostructure,
    primaryInteraction,
    mustHave,
    excluded,
    context,
    referenceArtifact,
  });
}

